// Regenerates src/countries/languages.ts: the main language of every measurable country.
// Usage: pnpm --filter @reranker/i18n generate:languages
import { writeFileSync } from "node:fs";
import { COUNTRY_CODES } from "../src/countries/codes.ts";
import { MAIN_LANGUAGE_OVERRIDES } from "../src/countries/policy.ts";

const OUTPUT = new URL("../src/countries/languages.ts", import.meta.url);
const COUNTRY_INFO = "https://download.geonames.org/export/dump/countryInfo.txt";

const response = await fetch(COUNTRY_INFO);
if (!response.ok) throw new Error(`GET ${COUNTRY_INFO} answered ${response.status}`);
const lastModified = response.headers.get("last-modified") ?? "unknown";

// GeoNames lists each country's languages by importance; the first one's language subtag is
// the language its people search in.
const listed = new Map<string, string>();
for (const line of (await response.text()).split("\n")) {
  if (line.startsWith("#") || line.trim() === "") continue;
  const columns = line.split("\t");
  const language = columns[15]?.split(",")[0]?.split("-")[0];
  if (columns[0] && language) listed.set(columns[0], language);
}

const missing: string[] = [];
const entries = COUNTRY_CODES.map((code) => {
  const language = MAIN_LANGUAGE_OVERRIDES[code] ?? listed.get(code);
  if (!language) missing.push(code);
  return `  ${code}: "${language}",`;
});
if (missing.length > 0)
  throw new Error(`No language in ${COUNTRY_INFO} for: ${missing.join(", ")}`);

writeFileSync(
  OUTPUT,
  [
    "// Generated by scripts/generate-languages.ts. Do not edit; rerun the script instead.",
    `// First language of ${COUNTRY_INFO} (last modified ${lastModified}),`,
    "// except MAIN_LANGUAGE_OVERRIDES (policy.ts).",
    'import type { CountryCode } from "./codes";',
    "",
    "export const MAIN_LANGUAGES: Readonly<Record<CountryCode, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n"),
);
console.log(`Wrote ${entries.length} languages to ${OUTPUT.pathname}`);
