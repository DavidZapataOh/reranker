import { writeFileSync } from "node:fs";

type Entry = { key: string; kind: string };

const list = (keys: string[]): string => keys.map((key) => `  "${key}",\n`).join("");

/** TypeScript keeps no literal types from a JSON import, so the key union is generated from it. */
export function renderFlagKeys(registry: readonly Entry[]): string {
  const keys = registry.map((f) => f.key);
  const switches = registry.filter((f) => f.kind === "kill-switch").map((f) => f.key);
  return `// Generated by \`pnpm --filter @reranker/flags flags:gen\` from registry.json. Do not edit.
export const FLAG_KEYS = [
${list(keys)}] as const;

export type FlagKey = (typeof FLAG_KEYS)[number];

export const KILL_SWITCH_KEYS = [
${list(switches)}] as const satisfies readonly FlagKey[];

export type KillSwitchKey = (typeof KILL_SWITCH_KEYS)[number];
`;
}

if (import.meta.main) {
  const { default: registry } = await import("../registry.json", { with: { type: "json" } });
  writeFileSync(new URL("../src/flag-keys.gen.ts", import.meta.url), renderFlagKeys(registry));
}
